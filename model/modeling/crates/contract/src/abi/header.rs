//! Deterministic C data-header rendering from canonical ABI metadata.

use core::convert::Infallible;

use hardware_interface_schema::export::{Artifact, ArtifactSink, Exporter};

mod constants;
mod generic;
mod mmio;
mod records;

/// PDMA-owned exporter for the complete ABI-v1 C data header.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct PdmaCHeaderExporter;

impl PdmaCHeaderExporter {
    /// Creates the stateless PDMA C-header exporter.
    #[must_use]
    pub const fn new() -> Self {
        Self
    }
}

impl Exporter<()> for PdmaCHeaderExporter {
    type Error = Infallible;

    fn export<Sink>(&self, _schema: &(), sink: &mut Sink) -> Result<(), Self::Error>
    where
        Sink: ArtifactSink<Error = Self::Error>,
    {
        sink.emit(Artifact {
            logical_name: String::from("pdma_model_abi.h"),
            media_type: String::from("text/x-c; charset=utf-8"),
            contents: render_c_header().into_bytes(),
        })
    }
}

/// Renders the complete generated C11 data header for ABI v1.
#[must_use]
pub fn render_c_header() -> String {
    let fragments = generic::render_fragments();
    let mut output = String::from(
        "/* Generated by pdma-abi-header; do not edit. */\n\
         #ifndef PDMA_MODEL_ABI_H\n\
         #define PDMA_MODEL_ABI_H\n\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n",
    );
    constants::push(&mut output);
    output.push('\n');
    records::push(&mut output, &fragments.records);
    mmio::push(&mut output, &fragments.mmio);
    output.push_str("#endif /* PDMA_MODEL_ABI_H */\n");
    output
}

#[cfg(test)]
mod tests {
    use super::render_c_header;

    #[test]
    fn renders_lf_only_and_records_byte_arrays() {
        // Given: the canonical ABI-v1 metadata registry.
        // When: the C data header is rendered twice.
        let first = render_c_header();
        let second = render_c_header();

        // Then: output is deterministic, LF-only, and exposes byte-array data records.
        assert_eq!(first, second);
        assert!(!first.contains('\r'));
        assert!(first.contains("uint8_t version[PDMA_MODEL_ABI_DESCRIPTOR_V1_VERSION_SIZE];"));
        assert!(first.contains("pdma_model_abi_indirect_destination_entry_v1"));
    }
}
