//! Deterministic C data-header rendering from canonical ABI metadata.

use core::fmt;

use hardware_interface_schema::export::{Artifact, ArtifactSink, Exporter};
use hardware_interface_schema::{
    RecordGraphError, RegisterMapError, ResolvedRecord, ResolvedRegisterMap,
};

use super::{
    AbiCommand, AbiCompletion, AbiEvent, IndirectDestinationEntrySchema,
    mmio::{PdmaMmioMap, PdmaMmioMapRegisterId},
};

mod constants;
mod generic;
mod mmio;
mod records;

/// PDMA-owned exporter for the complete ABI-v1 C data header.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq)]
pub struct PdmaCHeaderExporter;

/// Canonical resolved record and register graphs consumed by the PDMA exporter.
#[derive(Debug)]
pub struct PdmaHeaderSchemas {
    records: [ResolvedRecord; 4],
    mmio: ResolvedRegisterMap<PdmaMmioMapRegisterId>,
}

/// Failure while resolving canonical ABI schemas for header rendering.
#[derive(Debug)]
pub struct HeaderRenderError(HeaderSchemaError);

#[derive(Debug)]
enum HeaderSchemaError {
    Record(RecordGraphError),
    Map(RegisterMapError<PdmaMmioMapRegisterId>),
}

impl fmt::Display for HeaderRenderError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match &self.0 {
            HeaderSchemaError::Record(error) => {
                write!(formatter, "record schema resolution failed: {error:?}")
            }
            HeaderSchemaError::Map(error) => {
                write!(formatter, "register map resolution failed: {error:?}")
            }
        }
    }
}

impl std::error::Error for HeaderRenderError {}

impl PdmaCHeaderExporter {
    /// Creates the stateless PDMA C-header exporter.
    #[must_use]
    pub const fn new() -> Self {
        Self
    }

    /// Renders the exact PDMA C11 artifact from an already resolved schema bundle.
    #[must_use]
    pub fn render(&self, schemas: &PdmaHeaderSchemas) -> String {
        render_resolved(schemas)
    }
}

impl PdmaHeaderSchemas {
    /// Resolves every canonical graph required by the PDMA C11 policy.
    ///
    /// # Errors
    /// Returns a typed error when any record or register graph is structurally invalid.
    pub fn resolve() -> Result<Self, HeaderRenderError> {
        let resolve_record = |schema: hardware_interface_schema::RecordSpec| {
            schema
                .resolve()
                .map_err(|error| HeaderRenderError(HeaderSchemaError::Record(error)))
        };
        Ok(Self {
            records: [
                resolve_record(AbiCommand::SPEC)?,
                resolve_record(AbiCompletion::SPEC)?,
                resolve_record(AbiEvent::SPEC)?,
                resolve_record(IndirectDestinationEntrySchema::SPEC)?,
            ],
            mmio: PdmaMmioMap::resolve()
                .map_err(|error| HeaderRenderError(HeaderSchemaError::Map(error)))?,
        })
    }
}

impl Exporter<PdmaHeaderSchemas> for PdmaCHeaderExporter {
    type Error = HeaderRenderError;

    fn export<Sink>(&self, schemas: &PdmaHeaderSchemas, sink: &mut Sink) -> Result<(), Self::Error>
    where
        Sink: ArtifactSink<Error = Self::Error>,
    {
        sink.emit(Artifact {
            logical_name: String::from("pdma_model_abi.h"),
            media_type: String::from("text/x-c; charset=utf-8"),
            contents: self.render(schemas).into_bytes(),
        })
    }
}

/// Renders the complete generated C11 data header for ABI v1.
///
/// # Errors
/// Returns a typed error if a canonical schema no longer resolves.
pub fn render_c_header() -> Result<String, HeaderRenderError> {
    Ok(render_resolved(&PdmaHeaderSchemas::resolve()?))
}

fn render_resolved(schemas: &PdmaHeaderSchemas) -> String {
    let fragments = generic::project(schemas);
    let mut output = String::from(
        "/* Generated by pdma-abi-header; do not edit. */\n\
         #ifndef PDMA_MODEL_ABI_H\n\
         #define PDMA_MODEL_ABI_H\n\n\
         #include <stddef.h>\n\
         #include <stdint.h>\n\n",
    );
    constants::push(&mut output);
    output.push('\n');
    records::push(&mut output, &fragments.records);
    mmio::push(&mut output, &schemas.mmio);
    output.push_str("#endif /* PDMA_MODEL_ABI_H */\n");
    output
}

#[cfg(test)]
mod tests {
    use super::render_c_header;

    #[test]
    fn renders_lf_only_and_records_byte_arrays() {
        // Given: the canonical ABI-v1 metadata registry.
        // When: the C data header is rendered twice.
        let first = render_c_header().expect("canonical schemas must resolve");
        let second = render_c_header().expect("canonical schemas must resolve");

        // Then: output is deterministic, LF-only, and exposes byte-array data records.
        assert_eq!(first, second);
        assert!(!first.contains('\r'));
        assert!(first.contains("uint8_t version[PDMA_MODEL_ABI_DESCRIPTOR_V1_VERSION_SIZE];"));
        assert!(first.contains("pdma_model_abi_indirect_destination_entry_v1"));
    }
}
