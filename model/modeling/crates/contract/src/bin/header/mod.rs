use hardware_interface_schema::{
    export::backends::c_header::{RecordCHeaderExporter, RegisterMapCHeaderExporter},
    export::{Exporter, InMemoryArtifactSink},
};
use pdma_model_contract::control::{
    ControlEvent, ControlQueue, ControlRequest, ControlResponse, ControlRingState,
};
use pdma_model_contract::dma::{
    Command, CompletionInfo, DmaRegisters, Endpoint, Response, Segment,
};
use pdma_model_contract::hw_components::context::ContextTableRegisters;
use pdma_model_contract::hw_components::control::ControlRegisters;
use pdma_model_contract::hw_components::firmware::FirmwareRegisters;
use pdma_model_contract::hw_components::windows::ChannelWindowRegisters;
use pdma_model_contract::memory::ContextAttributes;
use pdma_model_contract::view::RegisterView;
use std::{error::Error, io::Write};

type HeaderSet = Vec<(&'static str, Vec<u8>)>;

/// Renders all role headers for one hardware channel count before file output.
pub fn generate(count: usize) -> Result<HeaderSet, Box<dyn Error>> {
    generate_with_contexts(count, count)
}

#[doc = "Renders role headers using independently specified channel and context capacity."]
pub fn generate_with_contexts(count: usize, contexts: usize) -> Result<HeaderSet, Box<dyn Error>> {
    u32::try_from(contexts)?;
    let layout = DmaRegisters::new(count)?;
    u32::try_from(count)?;
    u32::try_from(layout.extent())?;
    let windows = ChannelWindowRegisters::new(count)?;
    let contexts = ContextTableRegisters::for_channels(contexts, count)?;
    let registers = layout.resolve()?;
    let mut common = InMemoryArtifactSink::new();
    for (name, record) in [
        ("segment", Segment::SPEC.resolve()?),
        ("endpoint", Endpoint::SPEC.resolve()?),
        ("command", Command::SPEC.resolve()?),
        ("response", Response::SPEC.resolve()?),
        ("completioninfo", CompletionInfo::SPEC.resolve()?),
        ("contextattributes", ContextAttributes::SPEC.resolve()?),
        ("controlrequest", ControlRequest::SPEC.resolve()?),
        ("controlresponse", ControlResponse::SPEC.resolve()?),
        ("controlevent", ControlEvent::SPEC.resolve()?),
        ("controlringstate", ControlRingState::SPEC.resolve()?),
        ("controlqueue", ControlQueue::SPEC.resolve()?),
    ] {
        RecordCHeaderExporter::new(name, name).export(&record, &mut common)?;
    }
    let mut headers = vec![("pdma_common.h", wrap("PDMA_COMMON_H", &common, false))];
    for (role, prefix, filename, guard) in [
        (RegisterView::Host, "h", "pdma_host.h", "PDMA_HOST_H"),
        (
            RegisterView::Firmware,
            "f",
            "pdma_firmware.h",
            "PDMA_FIRMWARE_H",
        ),
    ] {
        let mut sink = InMemoryArtifactSink::new();
        if role == RegisterView::Firmware {
            RegisterMapCHeaderExporter::new("context", "fctx")
                .export(&contexts.resolve()?, &mut sink)?;
        }
        RegisterMapCHeaderExporter::new("dma", format!("{prefix}dma")).export(
            &registers.project_access(|r| role.dma_access(r.id(), r.definition().access()))?,
            &mut sink,
        )?;
        RegisterMapCHeaderExporter::new("boot", format!("{prefix}boot")).export(
            &FirmwareRegisters::resolve()?.project_access(|_| Some(role.boot_access()))?,
            &mut sink,
        )?;
        RegisterMapCHeaderExporter::new("control", format!("{prefix}ctl")).export(
            &ControlRegisters::resolve()?.project_access(|r| role.control_access(r.offset()))?,
            &mut sink,
        )?;
        let window_view = windows.resolve()?.project_access(|register| {
            let (_, offset) = windows.windows().locate_instance(register.offset())?;
            role.window_access(offset)
        })?;
        RegisterMapCHeaderExporter::new("window", format!("{prefix}win"))
            .export(&window_view, &mut sink)?;
        let mut bytes = wrap(guard, &sink, true);
        bytes.truncate(bytes.len() - b"#endif\n".len());
        let role_name = match role {
            RegisterView::Host => "HOST",
            RegisterView::Firmware => "FIRMWARE",
        };
        let window = windows.windows();
        writeln!(
            bytes,
            "#define PDMA_{role_name}_WINDOW_COUNT UINT32_C({})\n#define PDMA_{role_name}_WINDOW_STRIDE UINT32_C({})",
            window.count(),
            window.stride()
        )?;
        writeln!(bytes, "#endif")?;
        headers.push((filename, bytes));
    }
    Ok(headers)
}

fn wrap(guard: &str, sink: &InMemoryArtifactSink, common: bool) -> Vec<u8> {
    let mut bytes = format!("/* Generated by pdma-abi-header; do not edit. */\n#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n").into_bytes();
    if common {
        bytes.extend_from_slice(b"#include \"pdma_common.h\"\n");
    }
    for artifact in sink.artifacts() {
        bytes.extend_from_slice(&artifact.contents);
        bytes.push(b'\n');
    }
    bytes.extend_from_slice(b"#endif\n");
    bytes
}
