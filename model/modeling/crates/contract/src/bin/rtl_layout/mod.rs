use hw_model_schema::{
    analysis::{AnalyzedSchema, Bindings},
    ast::SchemaSet,
    export::{
        EntrySymbols, Kind,
        backends::veryl::{VerylRecordBackend, VerylRegisterBackend},
        record, register,
    },
};
use pdma_model_contract::dma::{Command, DmaRegisters, Event};
use std::{error::Error, io::Write};

#[cfg(test)]
mod tests;

/// Selects DMA roots and prepares them for the Veryl syntax renderer.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut definitions = SchemaSet::new();
    definitions.add::<Command>();
    definitions.add::<Event>();
    definitions.add::<DmaRegisters>();
    let schema = AnalyzedSchema::analyze(definitions, &Bindings::new())?;
    let mut bytes = Vec::new();
    emit_schema(&schema, &mut bytes)?;
    Ok(String::from_utf8(bytes)?)
}

fn emit_schema(schema: &AnalyzedSchema, writer: &mut dyn Write) -> Result<(), Box<dyn Error>> {
    let mut records = VerylRecordBackend::new();
    let mut registers = VerylRegisterBackend::new();
    let mut symbols = EntrySymbols::new();
    let record_outputs = symbols.prepare(
        &mut records,
        record::entries(schema)
            .filter(|v| v.definition_origin() == hw_model_schema::ast::Origin::Named),
    )?;
    let register_outputs = symbols.prepare(
        &mut registers,
        register::entries(schema)
            .filter(|visit| matches!(visit.entry_kind(), Kind::Register | Kind::RegisterMap)),
    )?;
    writer.write_all(b"// Generated by pdma-rtl-layout; do not edit.\n\n")?;
    for (index, output) in record_outputs.iter().enumerate() {
        if index != 0 {
            writer.write_all(b"\n")?;
        }
        output.emit(&mut records, writer)?;
    }
    for (index, output) in register_outputs.iter().enumerate() {
        if !record_outputs.is_empty() || index != 0 {
            writer.write_all(b"\n")?;
        }
        output.emit(&mut registers, writer)?;
    }
    Ok(())
}
