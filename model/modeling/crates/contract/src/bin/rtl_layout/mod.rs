use hw_model_schema::{
    export::{Exporter, InMemoryArtifactSink, backends::veryl::VerylLayoutExporter},
    graph::SchemaSet,
};
use pdma_model_contract::dma::{Command, DmaRegisters, Event};
use std::error::Error;

/// Selects DMA roots; the backend owns traversal, layout expressions and Veryl syntax.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut definitions = SchemaSet::new();
    definitions.add::<DmaRegisters>();
    definitions.add_record::<Command>();
    definitions.add_record::<Event>();
    let graph = definitions.resolve()?;
    let mut sink = InMemoryArtifactSink::new();
    VerylLayoutExporter::new().export(&graph, &mut sink)?;
    let mut text = String::from("// Generated by pdma-rtl-layout; do not edit.\n\n");
    for (index, artifact) in sink.into_artifacts().into_iter().enumerate() {
        if index != 0 {
            text.push('\n');
        }
        text.push_str(&String::from_utf8(artifact.contents)?);
    }
    Ok(text)
}
