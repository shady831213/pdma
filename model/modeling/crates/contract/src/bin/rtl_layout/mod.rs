mod emit;

use hw_model_schema::{RegisterShape, SchemaLayout};
use pdma_model_contract::dma::{
    ChannelAdmin, ChannelBlock, Command, CommandRegisters, DmaControl, DmaDiscovery, DmaRegisters,
    Event, EventRegisters,
};
use std::{error::Error, fmt::Write};

/// Renders fixed leaf metadata and count-dependent DMA bank geometry.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut text = String::from("// Generated by pdma-rtl-layout; do not edit.\n\n");
    emit::map(&mut text, "DiscoveryLayout", &DmaDiscovery::resolve()?)?;
    emit::map(&mut text, "ControlLayout", &DmaControl::resolve()?)?;
    emit::map(&mut text, "ChannelAdminLayout", &ChannelAdmin::resolve()?)?;
    emit::map(&mut text, "ChannelLayout", &ChannelBlock::resolve()?)?;
    emit::map(
        &mut text,
        "CommandRingLayout",
        &CommandRegisters::resolve()?,
    )?;
    emit::map(&mut text, "EventRingLayout", &EventRegisters::resolve()?)?;

    let layout = DmaRegisters::new(1)?;
    let admin = layout.admin();
    let resets = admin.child().channels();
    let admin_base = admin
        .base()
        .checked_add(resets.base())
        .ok_or("offset overflow")?;
    let channels = layout.channels();
    // This exporter assembles the same two-bank DMA topology, not a general schema compiler.
    // Check the algebra against the actual layout, including the admin/page boundary.
    for count in [1_usize, 2, 3, 16, 1019, 1020, 1021] {
        let actual = DmaRegisters::new(count)?;
        let end = count
            .checked_mul(resets.stride())
            .and_then(|size| admin_base.checked_add(size));
        let expected = end.and_then(|value| {
            hw_model_schema::checked_align_up(value, channels.child().alignment())
        });
        if expected != Some(actual.channels().base()) {
            return Err("DMA topology changed; update the RTL layout composition".into());
        }
    }
    writeln!(text, "#[fmt(skip)]\npub package DmaLayout {{")?;
    for (name, value) in [
        ("DISCOVERY_BASE", layout.discovery().base()),
        (
            "CONTROL_BASE",
            admin
                .base()
                .checked_add(admin.child().control().base())
                .ok_or("offset overflow")?,
        ),
        ("CHANNEL_ADMIN_BASE", admin_base),
        ("CHANNEL_ADMIN_STRIDE", resets.stride()),
        ("CHANNEL_ALIGNMENT", channels.child().alignment()),
        ("CHANNEL_STRIDE", channels.stride()),
        ("CHANNEL_COMMAND_OFFSET", ChannelBlock::COMMAND.offset()),
        ("CHANNEL_EVENT_OFFSET", ChannelBlock::EVENT.offset()),
        ("COMMAND_BYTES", Command::EXTENT),
        ("COMMAND_ALIGNMENT", Command::ALIGNMENT),
        ("EVENT_BYTES", Event::EXTENT),
        ("EVENT_ALIGNMENT", Event::ALIGNMENT),
    ] {
        writeln!(text, "    const {name}: u64 = {value};")?;
    }
    text.push_str("\n    function channel_base(channel_count: input u32) -> u64 {\n        return (CHANNEL_ADMIN_BASE + channel_count as u64 * CHANNEL_ADMIN_STRIDE + CHANNEL_ALIGNMENT - 1) & ~(CHANNEL_ALIGNMENT - 1);\n    }\n}\n");
    Ok(text)
}
