use hw_model_schema::analysis::{AnalyzedSchema, Bindings};
use hw_model_schema::{
    ast::{DescribeSchema, SchemaSet},
    export::{
        InMemoryArtifactSink,
        backends::veryl::{VerylRecordBackend, VerylRegisterBackend},
    },
};
use pdma_model_contract::dma::{Command, DmaRegisters, Event};
use std::{
    collections::{HashMap, hash_map::Entry},
    error::Error,
};

/// Selects DMA roots and prepares them for the Veryl syntax renderer.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut definitions = SchemaSet::new();
    let mut records = SchemaSet::new();
    let mut registers = SchemaSet::new();
    for definition in [Command::schema_definition(), Event::schema_definition()] {
        records.add_definition(definition.clone());
        definitions.add_definition(definition);
    }
    let dma = DmaRegisters::schema_definition();
    registers.add_definition(dma.clone());
    definitions.add_definition(dma);
    let graph = definitions.resolve()?;
    let mut sink = InMemoryArtifactSink::new();
    hw_model_schema::export::generate(
        &AnalyzedSchema::from_graph(&records.resolve()?, &Bindings::default())?,
        VerylRecordBackend::new(),
        &mut sink,
    )?;
    hw_model_schema::export::generate(
        &AnalyzedSchema::from_graph(&registers.resolve()?, &Bindings::default())?,
        VerylRegisterBackend::new(),
        &mut sink,
    )?;
    let mut packages = HashMap::new();
    for artifact in sink.into_artifacts() {
        match packages.entry(artifact.logical_name) {
            Entry::Vacant(entry) => {
                entry.insert(artifact.contents);
            }
            Entry::Occupied(entry) => {
                if entry.get() != &artifact.contents {
                    return Err("record and register exports disagree on a shared package".into());
                }
            }
        }
    }
    let mut text = String::from("// Generated by pdma-rtl-layout; do not edit.\n\n");
    for (index, definition) in graph.dependency_order().enumerate() {
        if index != 0 {
            text.push('\n');
        }
        let name = format!("{}Layout.veryl", definition.name());
        let contents = packages
            .remove(&name)
            .ok_or("missing or ambiguous layout package")?;
        text.push_str(&String::from_utf8(contents)?);
    }
    Ok(text)
}
