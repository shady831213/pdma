use hw_model_schema::{
    analysis::{AnalyzedSchema, Bindings},
    ast::SchemaSet,
    export::{Kind, backends::system_verilog::SvRegisterBackend, prepare_entries, register},
};
use pdma_model_contract::dma::DmaRegisters;
use std::{error::Error, io::Write};
/// Selects DMA register/map roots and streams independent SV layout packages.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut set = SchemaSet::new();
    set.add::<DmaRegisters>();
    let schema = AnalyzedSchema::analyze(set, &Bindings::new())?;
    let mut backend = SvRegisterBackend::new();
    let entries = prepare_entries(
        &mut backend,
        register::entries(&schema)
            .filter(|v| matches!(v.entry_kind(), Kind::Register | Kind::RegisterMap)),
    )?;
    let mut bytes = Vec::new();
    bytes.write_all(b"// Generated by pdma-sv-layout; do not edit.\n\n")?;
    for (index, entry) in entries.into_iter().enumerate() {
        if index != 0 {
            bytes.write_all(b"\n")?;
        }
        entry.emit(&mut backend, &mut bytes)?;
    }
    Ok(String::from_utf8(bytes)?)
}
