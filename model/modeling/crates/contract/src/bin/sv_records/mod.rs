use hw_model_schema::{
    analysis::{AnalyzedSchema, Bindings},
    ast::SchemaSet,
    export::{prepare_roots, record},
};
use pdma_model_contract::dma::{Command, Event};
use std::{error::Error, io::Write};
mod backend;
mod codec;
#[cfg(test)]
mod tests;

/// Exports the DMA record roots and their recursively discovered dependencies.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut definitions = SchemaSet::new();
    definitions.add::<Command>();
    definitions.add::<Event>();
    render(definitions)
}

fn render(definitions: SchemaSet) -> Result<String, Box<dyn Error>> {
    let schema = AnalyzedSchema::analyze(definitions, &Bindings::new())?;
    let mut backend = backend::SystemVerilog::default();
    let outputs = prepare_roots(&mut backend, record::roots(&schema))?;
    let mut bytes = Vec::new();
    bytes.write_all(
        b"// Generated by pdma-sv-records; do not edit.\n\
        // Byte n occupies bits [8*n +: 8]; scalar codecs honor schema endianness.\n\
        package pdma_contract_records;\n",
    )?;
    for output in outputs {
        output.emit(&mut backend, &mut bytes)?;
    }
    bytes.write_all(b"endpackage\n")?;
    Ok(String::from_utf8(bytes)?)
}
