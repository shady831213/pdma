use hw_model_schema::export::backends::uvm::UvmRegisterBackend;
use hw_model_schema::{
    analysis::{AnalyzedSchema, Bindings},
    ast::SchemaSet,
    export::{Kind, prepare_entries, register},
};
use pdma_model_contract::dma::DmaRegisters;
use std::{error::Error, io::Write};

/// Generates the DMA register package from the analyzed schema.
pub fn generate() -> Result<String, Box<dyn Error>> {
    let mut definitions = SchemaSet::new();
    definitions.add::<DmaRegisters>();
    render(definitions)
}

fn render(definitions: SchemaSet) -> Result<String, Box<dyn Error>> {
    let schema = AnalyzedSchema::analyze(definitions, &Bindings::new())?;
    let mut backend = UvmRegisterBackend::new();
    let outputs = prepare_entries(
        &mut backend,
        register::entries(&schema)
            .filter(|visit| matches!(visit.entry_kind(), Kind::Register | Kind::RegisterMap)),
    )?;
    let mut bytes = Vec::new();
    bytes.write_all(b"// Generated by pdma-uvm-regs; do not edit.\n// Schema access only: no inferred W1C or hardware side effects.\n// Volatile fields disable mirror comparison; PostReset has no known HARD reset.\n// Caller configures base, locks the model and installs adapter/sequencer.\npackage pdma_uvm_regs;\n  import uvm_pkg::*;\n  `include \"uvm_macros.svh\"\n")?;
    for output in outputs {
        output.emit(&mut backend, &mut bytes)?;
    }
    bytes.write_all(b"endpackage\n")?;
    Ok(String::from_utf8(bytes)?)
}

