//! Verifies indirect-list metadata provenance in the generated C header.

use pdma_model_contract::abi::{
    INDIRECT_DESTINATION_ENTRY, INDIRECT_DESTINATION_ENTRY_SIZE, INDIRECT_ENTRY_ALIGNMENT,
    header::render_c_header,
};

#[test]
fn indirect_destination_entry_metadata_drives_generated_header() {
    // Given: the canonical ABI-v1 indirect destination-list entry specification.
    let record = INDIRECT_DESTINATION_ENTRY;
    let [field] = record.fields() else {
        panic!("indirect destination entry must have exactly one field");
    };

    // When: the C data header is rendered from the canonical registry.
    let header = render_c_header();
    let field_name = field.name().to_ascii_uppercase();

    // Then: the fixed layout and generated byte-array macros agree with one metadata source.
    assert_eq!(INDIRECT_DESTINATION_ENTRY_SIZE, 8);
    assert_eq!(record.size(), INDIRECT_DESTINATION_ENTRY_SIZE);
    assert_eq!(record.alignment(), INDIRECT_ENTRY_ALIGNMENT);
    assert_eq!(field.name(), "destination_iova");
    assert_eq!((field.offset(), field.end()), (0, 8));
    assert!(header.contains(&format!(
        "#define PDMA_MODEL_ABI_INDIRECT_DESTINATION_ENTRY_SIZE UINT16_C({})",
        record.size()
    )));
    assert!(header.contains(&format!(
        "#define PDMA_MODEL_ABI_INDIRECT_DESTINATION_ENTRY_V1_{field_name}_OFFSET UINT16_C({})",
        field.offset()
    )));
    assert!(header.contains(&format!(
        "#define PDMA_MODEL_ABI_INDIRECT_DESTINATION_ENTRY_V1_{field_name}_SIZE UINT16_C({})",
        field.width()
    )));
}
