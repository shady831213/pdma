module records_roundtrip;
  import pdma_contract_records::*;
  CommandHeader_t header;
  CopyCommand_t copy_record;
  LinearEndpoint_t source_record, destination_record;
  FenceCommand_t fence_record;
  WordTarget_t target_record;
  WordWrite_t word_record;
  Command_t command_record;
  Event_t event_record;
  ErrorInfo_t error_record;
  initial begin
    header = '0;
    CommandHeader_set_opcode(header, COMMANDHEADER_OPCODE_COPY);
    copy_record = '0;
    CopyCommand_set_header(copy_record, header);
    CopyCommand_set_id(copy_record, 64'h123456789abcdef0);
    CopyCommand_set_copy_length(copy_record, 64'h0102030405060708);
    source_record = '0;
    LinearEndpoint_set_address(source_record, 64'h8877665544332211);
    LinearEndpoint_set_offset(source_record, 64'h1020304050607080);
    destination_record = '0;
    LinearEndpoint_set_address(destination_record, 64'hfedcba9876543210);
    LinearEndpoint_set_offset(destination_record, 64'h1122334455667788);
    CopyCommand_set_source(copy_record, source_record);
    CopyCommand_set_destination(copy_record, destination_record);
    command_record = copy_record;
    if (command_record !== @COPY@) $fatal(1, "Copy differs from Rust codec");
    header = '0;
    CommandHeader_set_opcode(header, COMMANDHEADER_OPCODE_FENCE);
    fence_record = '0;
    FenceCommand_set_header(fence_record, header);
    FenceCommand_set_id(fence_record, 64'h9988776655443322);
    target_record = '0;
    WordTarget_set_address(target_record, 64'h1234567887654320);
    WordTarget_set_width(target_record, WORDTARGET_WIDTH_BITS64);
    word_record = '0;
    WordWrite_set_target(word_record, target_record);
    WordWrite_set_value(word_record, 64'hf0e0d0c0b0a09080);
    FenceCommand_set_word(fence_record, word_record);
    command_record = fence_record;
    if (command_record !== @FENCE@) $fatal(1, "Fence differs from Rust codec");
    event_record = @EVENT@;
    if (Event_get_id(event_record) !== 64'hfedcba9876543210) $fatal(1, "Event identity");
    if (Event_get_code(event_record) !== EVENT_CODE_WRITEERROR) $fatal(1, "Event code");
    error_record = Event_get_info(event_record);
    if (ErrorInfo_get_bytes_completed(error_record) !== 64'h0123456789abcdef) $fatal(1, "Event prefix");
    $display("RECORD_CODEC_ORACLE_PASS Copy Fence Event");
    $finish;
  end
endmodule
