//! Register-ID dispatch for exact MMIO reads and writes.

use super::global::{self, GlobalRegister as G};
use super::irq::{self, IrqRegister as I};
use super::queue::{self, QueueRegister as Q};
use crate::device::DeviceCore;
use crate::register_file::MmioScalar;
use pdma_model_contract::abi::mmio::RegisterId;

pub(crate) const fn read(state: &DeviceCore, register: RegisterId) -> MmioScalar {
    match register {
        RegisterId::GMagic => global::read(state, G::Magic),
        RegisterId::GMmioAbiVersion => global::read(state, G::MmioAbiVersion),
        RegisterId::GReqAbiVersion => global::read(state, G::ReqAbiVersion),
        RegisterId::GReqFeatures => global::read(state, G::ReqFeatures),
        RegisterId::GResetExpectedEpoch => global::read(state, G::ResetExpectedEpoch),
        RegisterId::GCommand => global::read(state, G::Command),
        RegisterId::GResult => global::read(state, G::Result),
        RegisterId::GDetail0 => global::read(state, G::Detail0),
        RegisterId::GDetail1 => global::read(state, G::Detail1),
        RegisterId::GDetail2 => global::read(state, G::Detail2),
        RegisterId::GRspAbiVersion => global::read(state, G::RspAbiVersion),
        RegisterId::GRspRunState => global::read(state, G::RspRunState),
        RegisterId::GRspFeatures => global::read(state, G::RspFeatures),
        RegisterId::GRspEpoch => global::read(state, G::RspEpoch),
        RegisterId::GMaxRingDepth => global::read(state, G::MaxRingDepth),
        RegisterId::GMaxIndirectDestinations => global::read(state, G::MaxIndirectDestinations),
        RegisterId::GMaxTransferBytes => global::read(state, G::MaxTransferBytes),
        RegisterId::GMaxStridedRows => global::read(state, G::MaxStridedRows),
        RegisterId::GMaxStride => global::read(state, G::MaxStride),
        RegisterId::QExpectedEpoch => queue::read(state, Q::ExpectedEpoch),
        RegisterId::QId => queue::read(state, Q::Id),
        RegisterId::QExpectedCursor => queue::read(state, Q::ExpectedCursor),
        RegisterId::QNewCursor => queue::read(state, Q::NewCursor),
        RegisterId::QCfgSqDepth => queue::read(state, Q::CfgSqDepth),
        RegisterId::QCfgCqDepth => queue::read(state, Q::CfgCqDepth),
        RegisterId::QCfgEventPolicy => queue::read(state, Q::CfgEventPolicy),
        RegisterId::QCfgSoftwareOwner => queue::read(state, Q::CfgSoftwareOwner),
        RegisterId::QSqBase => queue::read(state, Q::SqBase),
        RegisterId::QSqDepth => queue::read(state, Q::SqDepth),
        RegisterId::QCqBase => queue::read(state, Q::CqBase),
        RegisterId::QCqDepth => queue::read(state, Q::CqDepth),
        RegisterId::QEqBase => queue::read(state, Q::EqBase),
        RegisterId::QEqDepth => queue::read(state, Q::EqDepth),
        RegisterId::QCommand => queue::read(state, Q::Command),
        RegisterId::QResult => queue::read(state, Q::Result),
        RegisterId::QDetail0 => queue::read(state, Q::Detail0),
        RegisterId::QDetail1 => queue::read(state, Q::Detail1),
        RegisterId::QDetail2 => queue::read(state, Q::Detail2),
        RegisterId::QRspEpoch => queue::read(state, Q::RspEpoch),
        RegisterId::QRspId => queue::read(state, Q::RspId),
        RegisterId::QRspSqProducer => queue::read(state, Q::RspSqProducer),
        RegisterId::QRspSqCaptured => queue::read(state, Q::RspSqCaptured),
        RegisterId::QRspSqConsumer => queue::read(state, Q::RspSqConsumer),
        RegisterId::QRspCqProducer => queue::read(state, Q::RspCqProducer),
        RegisterId::QRspCqConsumer => queue::read(state, Q::RspCqConsumer),
        RegisterId::QRspEqProducer => queue::read(state, Q::RspEqProducer),
        RegisterId::QRspEqConsumer => queue::read(state, Q::RspEqConsumer),
        RegisterId::IExpectedEpoch => irq::read(state, I::ExpectedEpoch),
        RegisterId::ISourceId => irq::read(state, I::SourceId),
        RegisterId::ISourceKind => irq::read(state, I::SourceKind),
        RegisterId::IRouteKind => irq::read(state, I::RouteKind),
        RegisterId::IRouteVector => irq::read(state, I::RouteVector),
        RegisterId::ICommand => irq::read(state, I::Command),
        RegisterId::IResult => irq::read(state, I::Result),
        RegisterId::IDetail0 => irq::read(state, I::Detail0),
        RegisterId::IDetail1 => irq::read(state, I::Detail1),
        RegisterId::IDetail2 => irq::read(state, I::Detail2),
        RegisterId::IRspEpoch => irq::read(state, I::RspEpoch),
        RegisterId::IRspSourceId => irq::read(state, I::RspSourceId),
        RegisterId::IRspSourceKind => irq::read(state, I::RspSourceKind),
        RegisterId::IRspState => irq::read(state, I::RspState),
        RegisterId::IRspRouteKind => irq::read(state, I::RspRouteKind),
        RegisterId::IRspNotificationKind => irq::read(state, I::RspNotificationKind),
        RegisterId::IRspVector => irq::read(state, I::RspVector),
        RegisterId::IRspMessageId => irq::read(state, I::RspMessageId),
        RegisterId::IRspPendingMessages => irq::read(state, I::RspPendingMessages),
    }
}

pub(crate) fn write(state: &mut DeviceCore, register: RegisterId, value: u64) {
    match register {
        RegisterId::GMagic => global::write(state, G::Magic, value),
        RegisterId::GMmioAbiVersion => global::write(state, G::MmioAbiVersion, value),
        RegisterId::GReqAbiVersion => global::write(state, G::ReqAbiVersion, value),
        RegisterId::GReqFeatures => global::write(state, G::ReqFeatures, value),
        RegisterId::GResetExpectedEpoch => global::write(state, G::ResetExpectedEpoch, value),
        RegisterId::GCommand => global::write(state, G::Command, value),
        RegisterId::GResult => global::write(state, G::Result, value),
        RegisterId::GDetail0 => global::write(state, G::Detail0, value),
        RegisterId::GDetail1 => global::write(state, G::Detail1, value),
        RegisterId::GDetail2 => global::write(state, G::Detail2, value),
        RegisterId::GRspAbiVersion => global::write(state, G::RspAbiVersion, value),
        RegisterId::GRspRunState => global::write(state, G::RspRunState, value),
        RegisterId::GRspFeatures => global::write(state, G::RspFeatures, value),
        RegisterId::GRspEpoch => global::write(state, G::RspEpoch, value),
        RegisterId::GMaxRingDepth => global::write(state, G::MaxRingDepth, value),
        RegisterId::GMaxIndirectDestinations => {
            global::write(state, G::MaxIndirectDestinations, value);
        }
        RegisterId::GMaxTransferBytes => global::write(state, G::MaxTransferBytes, value),
        RegisterId::GMaxStridedRows => global::write(state, G::MaxStridedRows, value),
        RegisterId::GMaxStride => global::write(state, G::MaxStride, value),
        RegisterId::QExpectedEpoch => queue::write(state, Q::ExpectedEpoch, value),
        RegisterId::QId => queue::write(state, Q::Id, value),
        RegisterId::QExpectedCursor => queue::write(state, Q::ExpectedCursor, value),
        RegisterId::QNewCursor => queue::write(state, Q::NewCursor, value),
        RegisterId::QCfgSqDepth => queue::write(state, Q::CfgSqDepth, value),
        RegisterId::QCfgCqDepth => queue::write(state, Q::CfgCqDepth, value),
        RegisterId::QCfgEventPolicy => queue::write(state, Q::CfgEventPolicy, value),
        RegisterId::QCfgSoftwareOwner => queue::write(state, Q::CfgSoftwareOwner, value),
        RegisterId::QSqBase => queue::write(state, Q::SqBase, value),
        RegisterId::QSqDepth => queue::write(state, Q::SqDepth, value),
        RegisterId::QCqBase => queue::write(state, Q::CqBase, value),
        RegisterId::QCqDepth => queue::write(state, Q::CqDepth, value),
        RegisterId::QEqBase => queue::write(state, Q::EqBase, value),
        RegisterId::QEqDepth => queue::write(state, Q::EqDepth, value),
        RegisterId::QCommand => queue::write(state, Q::Command, value),
        RegisterId::QResult => queue::write(state, Q::Result, value),
        RegisterId::QDetail0 => queue::write(state, Q::Detail0, value),
        RegisterId::QDetail1 => queue::write(state, Q::Detail1, value),
        RegisterId::QDetail2 => queue::write(state, Q::Detail2, value),
        RegisterId::QRspEpoch => queue::write(state, Q::RspEpoch, value),
        RegisterId::QRspId => queue::write(state, Q::RspId, value),
        RegisterId::QRspSqProducer => queue::write(state, Q::RspSqProducer, value),
        RegisterId::QRspSqCaptured => queue::write(state, Q::RspSqCaptured, value),
        RegisterId::QRspSqConsumer => queue::write(state, Q::RspSqConsumer, value),
        RegisterId::QRspCqProducer => queue::write(state, Q::RspCqProducer, value),
        RegisterId::QRspCqConsumer => queue::write(state, Q::RspCqConsumer, value),
        RegisterId::QRspEqProducer => queue::write(state, Q::RspEqProducer, value),
        RegisterId::QRspEqConsumer => queue::write(state, Q::RspEqConsumer, value),
        RegisterId::IExpectedEpoch => irq::write(state, I::ExpectedEpoch, value),
        RegisterId::ISourceId => irq::write(state, I::SourceId, value),
        RegisterId::ISourceKind => irq::write(state, I::SourceKind, value),
        RegisterId::IRouteKind => irq::write(state, I::RouteKind, value),
        RegisterId::IRouteVector => irq::write(state, I::RouteVector, value),
        RegisterId::ICommand => irq::write(state, I::Command, value),
        RegisterId::IResult => irq::write(state, I::Result, value),
        RegisterId::IDetail0 => irq::write(state, I::Detail0, value),
        RegisterId::IDetail1 => irq::write(state, I::Detail1, value),
        RegisterId::IDetail2 => irq::write(state, I::Detail2, value),
        RegisterId::IRspEpoch => irq::write(state, I::RspEpoch, value),
        RegisterId::IRspSourceId => irq::write(state, I::RspSourceId, value),
        RegisterId::IRspSourceKind => irq::write(state, I::RspSourceKind, value),
        RegisterId::IRspState => irq::write(state, I::RspState, value),
        RegisterId::IRspRouteKind => irq::write(state, I::RspRouteKind, value),
        RegisterId::IRspNotificationKind => irq::write(state, I::RspNotificationKind, value),
        RegisterId::IRspVector => irq::write(state, I::RspVector, value),
        RegisterId::IRspMessageId => irq::write(state, I::RspMessageId, value),
        RegisterId::IRspPendingMessages => irq::write(state, I::RspPendingMessages, value),
    }
}
