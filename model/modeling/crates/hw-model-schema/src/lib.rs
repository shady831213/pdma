extern crate self as hw_model_schema;

#[cfg(feature = "discovery")]
#[doc(hidden)]
pub use inventory as __inventory;

/// Registers generated metadata when discovery is enabled; ordinary builds add nothing.
#[doc(hidden)]
#[cfg(feature = "discovery")]
#[macro_export]
macro_rules! __register_schema {
    ($describe:expr) => {
        const _: () = {
            const DESCRIBE: fn() -> $crate::ast::Definition = $describe;
            let _ = DESCRIBE;
            $crate::__inventory::submit! { $crate::ast::Registration::new(DESCRIBE) }
        };
    };
}

#[doc(hidden)]
#[cfg(not(feature = "discovery"))]
#[macro_export]
macro_rules! __register_schema {
    ($describe:expr) => {
        const _: () = {
            const DESCRIBE: fn() -> $crate::ast::Definition = $describe;
            let _ = DESCRIBE;
        };
    };
}

